#!/usr/bin/env python3
"""Turn YOUR Smash T.V. ROMs into a C source file that is compiled into the app,
so the finished program needs no separate ROM file.

    embed_roms.py <smashtv.zip | folder of ROM files> <output.c>

Files are matched by CRC32, so odd file names are fine. The result contains the
ROM data: keep builds made with it on your own computers; don't share them.
"""
import io, sys, zipfile, zlib
from pathlib import Path

ROMSET = {  # name: (crc32, size), MAME "smashtv" rev 8.00
    "la1.u106": (0x5c718361, 131072), "la1.u107": (0x0fba1e36, 131072),
    "la1.u108": (0xcb0a092f, 131072), "la1.u111": (0x72f0ba84, 131072),
    "la1.u112": (0x436f0283, 131072), "la1.u113": (0x4a4b8110, 131072),
    "la1.u95": (0xe864a44b, 131072), "la1.u96": (0x15555ea7, 131072),
    "la1.u97": (0xccac9d9e, 131072), "sl2.u19": (0xac5a402a, 65536),
    "sl2.u20": (0x875c66d9, 65536), "sl2.u4": (0x29d3f6c8, 65536),
    "u105-la8": (0x48cd793f, 131072), "u89-la8": (0x8e7fe463, 131072),
}
BY_CRC = {crc: name for name, (crc, _) in ROMSET.items()}


def collect(src: Path) -> dict:
    found = {}

    def offer(data: bytes):
        name = BY_CRC.get(zlib.crc32(data) & 0xFFFFFFFF)
        if name and len(data) == ROMSET[name][1]:
            found.setdefault(name, data)

    def from_zip(z: zipfile.ZipFile):
        for info in z.infolist():
            if info.file_size in (65536, 131072):
                offer(z.read(info))

    if src.is_dir():
        for p in sorted(src.rglob("*")):
            if p.is_file() and p.suffix.lower() == ".zip":
                with zipfile.ZipFile(p) as z:
                    from_zip(z)
            elif p.is_file() and p.stat().st_size in (65536, 131072):
                offer(p.read_bytes())
    else:
        with zipfile.ZipFile(src) as z:
            from_zip(z)
    return found


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src, out = Path(sys.argv[1]).expanduser(), Path(sys.argv[2])
    found = collect(src)
    missing = [n for n in ROMSET if n not in found]
    if missing:
        sys.exit(f"embed_roms: {src} is missing or has wrong versions of: {', '.join(missing)}")
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for name in sorted(ROMSET):
            info = zipfile.ZipInfo(name, date_time=(1990, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            z.writestr(info, found[name])
    data = buf.getvalue()
    lines = ["/* Generated by scripts/embed_roms.py - contains ROM data; do not distribute. */",
             "#include <stddef.h>",
             f"const size_t smashtv_embedded_zip_size = {len(data)};",
             "const unsigned char smashtv_embedded_zip[] = {"]
    for i in range(0, len(data), 24):
        lines.append(",".join(str(b) for b in data[i:i + 24]) + ",")
    lines.append("};")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print(f"embed_roms: embedded all {len(ROMSET)} ROM files ({len(data)} bytes) from {src}")


if __name__ == "__main__":
    main()
